CREATE TABLE recruiting_profile_repair_sessions (
  session_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  active_session_key VARCHAR(384) CHARACTER SET ascii COLLATE ascii_bin NULL,
  profile_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  profile_version BIGINT UNSIGNED NOT NULL,
  incident_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  work_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  requested_by VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  device_actor_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  attempt_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NULL,
  validation_work_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NULL,
  session_status VARCHAR(32) CHARACTER SET ascii NOT NULL,
  expires_at DATETIME(6) NOT NULL,
  version BIGINT UNSIGNED NOT NULL,
  state_json JSON NOT NULL,
  created_at DATETIME(6) NOT NULL,
  updated_at DATETIME(6) NOT NULL,
  PRIMARY KEY (session_id),
  UNIQUE KEY uq_recruiting_profile_repair_active (active_session_key),
  UNIQUE KEY uq_recruiting_profile_repair_work (work_id),
  KEY ix_recruiting_profile_repair_expiry (session_status, expires_at, session_id),
  KEY ix_recruiting_profile_repair_incident (incident_id, session_id),
  CONSTRAINT fk_recruiting_profile_repair_profile FOREIGN KEY (profile_id) REFERENCES recruiting_profiles(profile_id),
  CONSTRAINT fk_recruiting_profile_repair_incident FOREIGN KEY (incident_id) REFERENCES recruiting_repair_incidents(incident_id),
  CONSTRAINT fk_recruiting_profile_repair_work FOREIGN KEY (work_id) REFERENCES recruiting_works(work_id),
  CONSTRAINT fk_recruiting_profile_repair_attempt FOREIGN KEY (attempt_id) REFERENCES recruiting_attempts(attempt_id),
  CONSTRAINT fk_recruiting_profile_repair_validation_work FOREIGN KEY (validation_work_id) REFERENCES recruiting_works(work_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
